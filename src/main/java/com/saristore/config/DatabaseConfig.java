package com.saristore.config;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

public final class DatabaseConfig {

    private DatabaseConfig() {}

    private static String getDatabaseUrl() {
        // Automatically resolves to the app's internal writable directory across Desktop and Mobile
        String userHome = System.getProperty("user.home");
        Path dbDirectory = Path.of(userHome, ".saristore");

        try {
            Files.createDirectories(dbDirectory);
        } catch (Exception e) {
            e.printStackTrace();
        }

        String dbPath = dbDirectory.resolve("saristore").toAbsolutePath().toString();
        return "jdbc:h2:file:" + dbPath + ";AUTO_SERVER=TRUE";
    }

    public static Connection connect() throws SQLException {
        return DriverManager.getConnection(getDatabaseUrl(), "sa", "");
    }

    public static void initialize() throws Exception {
        try (Connection c = connect(); Statement s = c.createStatement()) {
            s.execute("CREATE TABLE IF NOT EXISTS products (" +
                    "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                    "barcode VARCHAR(50) UNIQUE, " +
                    "product_name VARCHAR(100) NOT NULL, " +
                    "category VARCHAR(50), " +
                    "cost_price DECIMAL(10,2) NOT NULL DEFAULT 0, " +
                    "selling_price DECIMAL(10,2) NOT NULL DEFAULT 0, " +
                    "stock_quantity INT NOT NULL DEFAULT 0, " +
                    "low_stock_threshold INT NOT NULL DEFAULT 5, " +
                    "units_per_pack INT NOT NULL DEFAULT 1, " +
                    "stock_unit VARCHAR(30) NOT NULL DEFAULT 'piece', " +
                    "sell_unit VARCHAR(30) NOT NULL DEFAULT 'piece')");

            s.execute("CREATE TABLE IF NOT EXISTS customers (" +
                    "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                    "name VARCHAR(100) NOT NULL, " +
                    "phone VARCHAR(20), " +
                    "address VARCHAR(200), " +
                    "current_debt DECIMAL(10,2) NOT NULL DEFAULT 0)");

            s.execute("CREATE TABLE IF NOT EXISTS sales (" +
                    "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                    "sale_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, " +
                    "total_amount DECIMAL(10,2) NOT NULL, " +
                    "payment_type VARCHAR(10) NOT NULL CHECK (payment_type IN ('CASH','CREDIT')), " +
                    "customer_id INT REFERENCES customers(id), " +
                    "amount_tendered DECIMAL(10,2) NOT NULL DEFAULT 0)");

            s.execute("CREATE TABLE IF NOT EXISTS sale_items (" +
                    "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                    "sale_id INT NOT NULL REFERENCES sales(id), " +
                    "product_id INT NOT NULL REFERENCES products(id), " +
                    "quantity INT NOT NULL, " +
                    "unit_price DECIMAL(10,2) NOT NULL, " +
                    "unit_cost DECIMAL(10,2) NOT NULL DEFAULT 0)");

            s.execute("CREATE TABLE IF NOT EXISTS credit_payments (" +
                    "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                    "customer_id INT NOT NULL REFERENCES customers(id), " +
                    "amount_paid DECIMAL(10,2) NOT NULL, " +
                    "payment_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, " +
                    "notes VARCHAR(250))");
        }
    }
}